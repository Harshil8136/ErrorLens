#!/usr/bin/env node
/**
 * Compiles datasets/runbooks/*.md into a numbered D1 migration.
 *
 * This is the step that was missing: the old pipeline wrote a
 * `generated_seed.sql` that no migration and no code path ever read, so a
 * contributed runbook could pass review and still never reach the database.
 *
 * Idempotent -- if the generated SQL matches the newest generated migration,
 * nothing is written and no new file appears in a diff.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RunbookError, parseRunbook } from './lib/parse-runbook.js';

const runbooksDir = fileURLToPath(new URL('../runbooks', import.meta.url));
const migrationsDir = fileURLToPath(new URL('../../worker/migrations', import.meta.url));

const HEADER = '-- Generated by datasets/scripts/build-migration.js -- do not edit by hand.';

/** SQLite escapes a single quote by doubling it; there are no backslash escapes. */
function quote(value) {
  if (value === null || value === undefined) return 'NULL';
  return `'${String(value).replace(/'/g, "''")}'`;
}

function buildSql(runbooks) {
  const today = new Date().toISOString().slice(0, 10);
  const rows = runbooks
    .map((r) =>
      [
        '  (',
        `    ${quote(r.slug)},`,
        `    ${quote(r.category)},`,
        `    ${quote(r.error_code)},`,
        `    ${quote(r.title)},`,
        `    ${quote(r.summary)},`,
        `    ${quote(r.root_cause)},`,
        `    ${quote(r.diagnostic_command)},`,
        `    ${quote(r.solution_steps)},`,
        `    ${quote(r.tags)},`,
        `    ${quote(r.source_url)},`,
        `    ${quote(r.verified_at ?? today)}`,
        '  )',
      ].join('\n')
    )
    .join(',\n');

  return `${HEADER}
-- Source: datasets/runbooks/*.md  (${runbooks.length} entries)
--
-- INSERT OR REPLACE keyed on slug, so re-running an updated runbook edits the
-- existing row rather than creating a duplicate.

INSERT OR REPLACE INTO runbooks (
  slug, category, error_code, title, summary, root_cause,
  diagnostic_command, solution_steps, tags, source_url, verified_at
) VALUES
${rows};
`;
}

function nextMigrationNumber() {
  const numbers = readdirSync(migrationsDir)
    .filter((f) => /^\d{4}_/.test(f))
    .map((f) => Number.parseInt(f.slice(0, 4), 10));
  return String(Math.max(0, ...numbers) + 1).padStart(4, '0');
}

function newestGenerated() {
  const generated = readdirSync(migrationsDir)
    .filter((f) => /^\d{4}_runbooks_/.test(f))
    .sort();
  const latest = generated.at(-1);
  return latest ? { name: latest, sql: readFileSync(join(migrationsDir, latest), 'utf8') } : null;
}

function main() {
  const files = readdirSync(runbooksDir)
    .filter((f) => f.endsWith('.md'))
    .sort();

  if (files.length === 0) {
    console.log('No runbooks found; nothing to build.');
    return 0;
  }

  const runbooks = [];
  for (const file of files) {
    try {
      runbooks.push(parseRunbook(readFileSync(join(runbooksDir, file), 'utf8')));
    } catch (err) {
      const message = err instanceof RunbookError ? err.message : String(err);
      console.error(`${file}: ${message}`);
      console.error('\nRun `npm run runbooks:validate` for the full report.');
      return 1;
    }
  }

  const sql = buildSql(runbooks);
  const previous = newestGenerated();

  // Compare ignoring the entry-count comment line, which changes with content
  // anyway, so an unchanged corpus never produces a spurious file.
  if (previous && previous.sql.trim() === sql.trim()) {
    console.log(`No changes: ${previous.name} is already up to date.`);
    return 0;
  }

  const name = `${nextMigrationNumber()}_runbooks_${new Date().toISOString().slice(0, 10).replace(/-/g, '')}.sql`;
  writeFileSync(join(migrationsDir, name), sql, 'utf8');

  console.log(`Wrote worker/migrations/${name} (${runbooks.length} runbooks).`);
  console.log('\nNext:');
  console.log('  npx wrangler d1 migrations apply errorlens-db --local   # or --remote');
  console.log('  curl -X POST <worker>/api/admin/reindex -H "Authorization: Bearer $ADMIN_TOKEN"');
  return 0;
}

process.exit(main());
